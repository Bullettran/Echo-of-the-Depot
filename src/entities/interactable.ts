/**
 * Всё, что можно «трогать» по E. Реализуют ResourceNode (W1.2),
 * дальше — станция-модули, верстак, двери (WEB_PLAN §4, аналог BPI_Interact).
 */
export interface I_Interactable {
  /** Подпись для промпта: «Собрать: Куча металлолома». */
  getLabel(): string
  /** Доступна ли для взаимодействия прямо сейчас (истощённая нода — нет). */
  IsAvailable(): boolean
  /** Выполнить действие. Валидация (место в рюкзаке и т.п.) — внутри реализации. */
  interact(): void
  /** Центр объекта в мировых координатах (для поиска ближайшего). */
  getInteractCenter(): { x: number; y: number }
}
